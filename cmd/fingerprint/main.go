// fingerprint prints the code fingerprint of a binary and any known software
// IDs sharing it, or regenerates the database:
//
//	fingerprint <file.bin>
//	fingerprint scan <dir>...      identify every .bin below the dirs
//	fingerprint gen <out.go> <dir>...
package main

import (
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"sort"
	"strings"

	symbol "github.com/roffe/ecusymbol"
)

func main() {
	if len(os.Args) > 3 && os.Args[1] == "gen" {
		if err := gen(os.Args[2], os.Args[3:]); err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
		return
	}
	if len(os.Args) > 2 && os.Args[1] == "scan" {
		for _, root := range os.Args[2:] {
			filepath.WalkDir(root, func(p string, d fs.DirEntry, err error) error {
				if err == nil && !d.IsDir() && strings.EqualFold(filepath.Ext(p), ".bin") {
					_, ff, err := load(p)
					if err != nil {
						fmt.Printf("ERR\t\t%s\t%v\n", p, err)
						return nil
					}
					sw, score := symbol.Identify(ff)
					fmt.Printf("%.3f\t%s\t%q\t%v\n", score, p, ff.Version(), sw)
				}
				return nil
			})
		}
		return
	}
	if len(os.Args) != 2 {
		fmt.Fprintln(os.Stderr, "usage: fingerprint <file.bin> | fingerprint scan <dir>... | fingerprint gen <out.go> <dir>...")
		os.Exit(2)
	}
	_, ff, err := load(os.Args[1])
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	sw, score := symbol.Identify(ff)
	fmt.Printf("%s match=%.3f %v\n", ff.Version(), score, sw)
}

func load(name string) (symbol.Fingerprinter, symbol.FirmwareFile, error) {
	data, err := os.ReadFile(name)
	if err != nil {
		return nil, nil, err
	}
	_, ff, err := symbol.Load(name, data, func(string) {})
	if err != nil {
		return nil, nil, fmt.Errorf("%s: %w", filepath.Base(name), err)
	}
	fp, ok := ff.(symbol.Fingerprinter)
	if !ok {
		return nil, nil, fmt.Errorf("%s: no fingerprint support", filepath.Base(name))
	}
	return fp, ff, nil
}

// partNumber is the leading digits of a reference binary's filename.
var partNumber = regexp.MustCompile(`^\d+`)

func gen(out string, dirs []string) error {
	db := map[string]map[string][]string{} // fingerprint -> software ID -> part numbers
	for _, dir := range dirs {
		files, _ := filepath.Glob(filepath.Join(dir, "*"))
		for _, f := range files {
			fp, ff, err := load(f)
			if err != nil {
				fmt.Fprintln(os.Stderr, "skip:", err)
				continue
			}
			k := fp.CodeFingerprint()
			if db[k] == nil {
				db[k] = map[string][]string{}
			}
			v, pn := ff.Version(), partNumber.FindString(filepath.Base(f))
			if _, ok := db[k][v]; !ok {
				db[k][v] = nil
			}
			if pn != "" && !slices.Contains(db[k][v], pn) {
				db[k][v] = append(db[k][v], pn)
			}
		}
	}
	keys := make([]string, 0, len(db))
	for k := range db {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	w, err := os.Create(out)
	if err != nil {
		return err
	}
	defer w.Close()
	fmt.Fprintln(w, "// Code generated by cmd/fingerprint; DO NOT EDIT.\n\npackage symbol\n\nvar knownFingerprints = []fingerprintEntry{")
	for _, k := range keys {
		ids := make([]string, 0, len(db[k]))
		for id := range db[k] {
			ids = append(ids, id)
		}
		sort.Strings(ids)
		fmt.Fprintf(w, "\t{%q, []Software{\n", k)
		for _, id := range ids {
			sort.Strings(db[k][id])
			fmt.Fprintf(w, "\t\t{%q, %#v},\n", id, db[k][id])
		}
		fmt.Fprintln(w, "\t}},")
	}
	fmt.Fprintln(w, "}")
	return nil
}
